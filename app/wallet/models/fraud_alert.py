"""
Fraud Alert Model

Stores fraud alerts generated by suspicious activity monitoring.
Admins review and act on these alerts.
"""

from datetime import datetime
from sqlalchemy import (
    Column, String, Numeric, DateTime, Text, Boolean,
    ForeignKey, Index, BigInteger, CheckConstraint
)
from sqlalchemy.dialects.postgresql import JSONB
from app.extensions import db


FRAUD_ALERT_STATUS_VALUES = ('open', 'reviewing', 'resolved', 'dismissed', 'escalated')
FRAUD_ALERT_ACTION_VALUES = (
    'send_funds', 'withdraw_funds', 'deposit', 'transfer',
    'change_email', 'change_phone', 'change_password', 'wallet_activation'
)


class FraudAlert(db.Model):
    """
    Fraud alert generated by suspicious activity monitoring.
    
    Tracks potentially fraudulent transactions and user actions
    for admin review and intervention.
    """
    __tablename__ = 'fraud_alerts'
    __table_args__ = (
        CheckConstraint(
            f"status IN {FRAUD_ALERT_STATUS_VALUES}",
            name='ck_fraud_alert_status_valid'
        ),
        CheckConstraint(
            f"action IN {FRAUD_ALERT_ACTION_VALUES}",
            name='ck_fraud_alert_action_valid'
        ),
        CheckConstraint('risk_score >= 0 AND risk_score <= 100', name='ck_fraud_alert_risk_score_range'),
        Index('ix_fraud_alert_user_id', 'user_id'),
        Index('ix_fraud_alert_status', 'status'),
        Index('ix_fraud_alert_risk_score', 'risk_score'),
        Index('ix_fraud_alert_created_at', 'created_at'),
        Index('ix_fraud_alert_transaction_id', 'transaction_id'),
    )

    id = Column(
        BigInteger,
        primary_key=True,
        autoincrement=True
    )
    
    user_id = Column(
        BigInteger,
        ForeignKey('users.id', ondelete='CASCADE'),
        nullable=False,
        index=True
    )
    
    transaction_id = Column(
        String(64),
        nullable=True,
        index=True
    )
    
    action = Column(
        String(50),
        nullable=False
    )
    
    risk_score = Column(
        Numeric(5, 2),
        nullable=False
    )
    
    patterns = Column(
        JSONB,
        nullable=False,
        default=list
    )
    
    details = Column(
        JSONB,
        nullable=False,
        default=dict
    )
    
    status = Column(
        String(20),
        nullable=False,
        default='open'
    )
    
    reviewed_by = Column(
        BigInteger,
        ForeignKey('users.id', ondelete='SET NULL'),
        nullable=True
    )
    
    reviewed_at = Column(
        DateTime(timezone=True),
        nullable=True
    )
    
    resolution_notes = Column(
        Text,
        nullable=True
    )
    
    created_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=datetime.utcnow
    )
    
    updated_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=datetime.utcnow,
        onupdate=datetime.utcnow
    )

    def __repr__(self):
        return (
            f"<FraudAlert {self.id} user={self.user_id} "
            f"action={self.action} score={self.risk_score} status={self.status}>"
        )

    def to_dict(self):
        """Convert to dictionary for JSON serialization."""
        return {
            'id': self.id,
            'user_id': self.user_id,
            'transaction_id': self.transaction_id,
            'action': self.action,
            'risk_score': float(self.risk_score) if self.risk_score else 0,
            'patterns': self.patterns or [],
            'details': self.details or {},
            'status': self.status,
            'reviewed_by': self.reviewed_by,
            'reviewed_at': self.reviewed_at.isoformat() if self.reviewed_at else None,
            'resolution_notes': self.resolution_notes,
            'created_at': self.created_at.isoformat() if self.created_at else None,
            'updated_at': self.updated_at.isoformat() if self.updated_at else None,
        }
